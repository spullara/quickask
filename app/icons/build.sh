#!/usr/bin/env bash
# Regenerate src/icons.ts from logo.svg. Needs rsvg-convert (brew install librsvg).
set -euo pipefail
cd "$(dirname "$0")"
tmp="$(mktemp -d)"
# iOS rounds the home-screen icon itself, so that one is a full square.
sed 's/rx="15"/rx="0"/' logo.svg > "$tmp/square.svg"
rsvg-convert -w 32 -h 32 logo.svg -o "$tmp/favicon.png"
rsvg-convert -w 180 -h 180 "$tmp/square.svg" -o "$tmp/apple.png"
{
  echo "// Generated by icons/build.sh from icons/logo.svg. Do not edit."
  printf 'export const LOGO_SVG = %s;\n' "$(jq -Rs . < logo.svg)"
  printf 'export const FAVICON_PNG = "%s";\n' "$(base64 < "$tmp/favicon.png" | tr -d '\n')"
  printf 'export const APPLE_ICON_PNG = "%s";\n' "$(base64 < "$tmp/apple.png" | tr -d '\n')"
} > ../src/icons.ts
rm -rf "$tmp"
